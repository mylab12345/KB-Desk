// Tests for the browser's pure-JS end-to-end crypto (crates/kbdesk-web/web/crypto.js).
// Run: node tests/js/crypto.test.cjs   (also a CI step)
"use strict";
const assert = require("node:assert");
const K = require("../../crates/kbdesk-web/web/crypto.js");
const { hex, unhex, utf8 } = K;

let passed = 0;
function eq(actual, expected, label) {
  assert.strictEqual(actual, expected, label);
  passed++;
  console.log("PASS", label);
}

// SHA-256("abc")
eq(hex(K.sha256(utf8("abc"))),
   "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad",
   "sha256");

// HKDF RFC 5869 test case 1
{
  const ikm = new Uint8Array(22).fill(0x0b);
  const salt = unhex("000102030405060708090a0b0c");
  const info = unhex("f0f1f2f3f4f5f6f7f8f9");
  const prk = K.hkdfExtract(salt, ikm);
  eq(hex(prk), "077709362c2e32df0ddc3f0dc47bba6390b6c73bb50f9c3122ec844ad7c2b3e5", "hkdf prk");
  eq(hex(K.hkdfExpand(prk, info, 42)),
     "3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56ecc4c5bf34007208d5b887185865",
     "hkdf okm");
}

// X25519 RFC 7748 section 6.1 (Alice/Bob)
{
  const alicePriv = unhex("77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a");
  const bobPub = unhex("de9edb7d7b7dc1b4d35b61c2ece435373f8343c85b78674dadfc7e146f882b4f");
  eq(hex(K.publicFromSecret(alicePriv)),
     "8520f0098930a754748b7ddcb43ef75a0dbf3a0d26381af4eba4a98eaa9b4e6a", "x25519 public");
  eq(hex(K.x25519(alicePriv, bobPub)),
     "4a5d9d5ba4ce2de1728e3bf480350f25e07e21c947d19e3376f09b3c1e161742", "x25519 shared");
}

// ChaCha20-Poly1305 RFC 8439 A.5
{
  const key = unhex("808182838485868788898a8b8c8d8e8f909192939495969798999a9b9c9d9e9f");
  const nonce = unhex("070000004041424344454647");
  const aad = unhex("50515253c0c1c2c3c4c5c6c7");
  const pt = utf8("Ladies and Gentlemen of the class of '99: If I could offer you only one tip for the future, sunscreen would be it.");
  const ct = K.aeadEncrypt(key, nonce, pt, aad);
  eq(hex(ct),
     "d31a8d34648e60db7b86afbc53ef7ec2a4aded51296e08fea9e2b5a736ee62d63dbea45e8ca9671282fafb69da92728b1a71de0a9e060b2905d6a5b67ecd3b3692ddbd7f2d778b8c9803aee328091b58fab324e4fad675945585808b4831d7bc3ff4def08e4b7a9de576d26586cec64b61161ae10b594f09e26a7e902ecbd0600691",
     "aead encrypt");
  eq(new TextDecoder().decode(K.aeadDecrypt(key, nonce, ct, aad)),
     new TextDecoder().decode(pt), "aead decrypt roundtrip");
  const tampered = new Uint8Array(ct); tampered[0] ^= 1;
  assert.throws(() => K.aeadDecrypt(key, nonce, tampered, aad), /authentication/);
  passed++; console.log("PASS aead tamper rejected");
}

// KB-Desk v2 session vector (generated by tests/e2e/kb_crypto.py; the same
// constants are asserted in kbdesk-core's Rust tests).
{
  const viewerSecret = unhex("a546e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449ac4");
  const hostSecret = unhex("4b66e9d4d1b4673c5ad22691957d6af5c11b6421e0ea01d42ca4169e7918ba0d");
  const viewerPub = K.publicFromSecret(viewerSecret);
  const hostPub = K.publicFromSecret(hostSecret);
  eq(hex(viewerPub), "1c9fd88f45606d932a80c71824ae151d15d73e77de38e8e000852e614fae7019", "vector viewer pub");
  eq(hex(hostPub), "ff63fe57bfbf43fa3f563628b149af704d3db625369c49983650347a6a71e00e", "vector host pub");

  const base = {
    clientPublic: viewerPub, hostPublic: hostPub,
    clientNonce: unhex("000102030405060708090a0b0c0d0e0f"),
    hostNonce: unhex("101112131415161718191a1b1c1d1e1f"),
    hostId: "544228382", password: "correct horse battery staple",
  };
  const v = K.deriveSession({ ...base, mySecret: viewerSecret, peerPublic: hostPub, iAmViewer: true });
  const h = K.deriveSession({ ...base, mySecret: hostSecret, peerPublic: viewerPub, iAmViewer: false });
  eq(hex(v.myConfirm), "ad8940072fe15eba71f387830fdc88107dc2ac732a0447ef040b2792f7b8b46b", "vector confirm viewer");
  eq(hex(v.peerConfirm), "c986bae686b94483414ecb3953e1b34a127b40e4c4573140aba8e681697e33f0", "vector confirm host");
  assert.ok(K.ctEq(v.myConfirm, h.peerConfirm) && K.ctEq(v.peerConfirm, h.myConfirm));

  const wire1 = v.send.encrypt(1, utf8('{"StartStream":{"monitor":0,"quality":70,"fps":15}}'));
  eq(hex(wire1),
     "0000000000000000e314b7b98a172751bf83ec6ddc6e90b703e5629dddbc17fe8c994c496821a5dd1c56bebef2d86646d3e2d4543eab15c01303f8486fd655ee6158eabdac9f2c68c33ab1",
     "vector frame viewer->host #0");
  eq(new TextDecoder().decode(h.recv.decrypt(1, wire1)),
     '{"StartStream":{"monitor":0,"quality":70,"fps":15}}', "vector frame1 decrypts at host");

  const pt2 = unhex("0780043800ffd866616b656a706567ffd9");
  const wire2 = h.send.encrypt(2, pt2);
  eq(hex(wire2), "00000000000000004f468e3b56610c7b004e0fd618300159b634956b80c7b070493a7e2a0969c7eb69",
     "vector frame host->viewer #0");
  eq(hex(v.recv.decrypt(2, wire2)), hex(pt2), "vector frame2 decrypts at viewer");

  const wire3 = h.send.encrypt(1, utf8('{"Pong":424242}'));
  eq(hex(wire3), "00000000000000012916706919a09561815ec8c511897ccdf403fd015dc198067ab6fdfea7b184",
     "vector frame host->viewer #1 (counter)");

  // Wrong password derives different confirms (auth failure signal).
  const wrong = K.deriveSession({ ...base, password: "wrong", mySecret: viewerSecret, peerPublic: hostPub, iAmViewer: true });
  assert.ok(!K.ctEq(wrong.peerConfirm, h.myConfirm));
  passed++; console.log("PASS wrong password != host confirm");

  // Replay of an earlier frame is rejected by the counter check.
  assert.throws(() => v.recv.decrypt(2, wire2), /out of order/);
  passed++; console.log("PASS replay rejected");
}

console.log(`ALL ${passed} CHECKS PASS`);
